"""Generate the command-line reference page from docs/cli_options.toml.

    python docs/tools/gen_cli_reference.py            # write docs/source/cli_reference.rst
    python docs/tools/gen_cli_reference.py --check    # fail if the page is stale, or if the
                                                      # option table and the CLI disagree

The option table is hand-written: each entry's default, requirement and effect is taken from the
code that applies it, with the evidence recorded next to it. --check keeps the table honest about
which options exist: every option defined in src/nyx/cli_option_constants.h must have an entry,
and every entry must name an option the CLI defines. Every entry's evidence must cite files and
line ranges that exist. Every single-token default must be the value assigned on the one line its
`default_at` key names (`default_at = "-"` opts an entry out). A default that changes in the code
fails the check; a citation that drifts to a different line fails it unless the new line assigns
the same value.
"""

import argparse
import math
import re
import sys
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TABLE = REPO / "docs" / "cli_options.toml"
HEADER = REPO / "src" / "nyx" / "cli_option_constants.h"
PAGE = REPO / "docs" / "source" / "cli_reference.rst"

# Options handled in parse_cmdline() itself rather than through a clo_* constant.
BUILTIN = {"-h", "--help"}

GROUPS = [
    "Input",
    "Output",
    "Features",
    "Texture settings",
    "Gabor",
    "Image handling",
    "Performance and memory",
    "Nested ROIs",
    "Diagnostics",
    "GPU",
]


def cli_options():
    """Option names defined by the CLI: every clo_* constant whose value starts with a dash."""
    text = HEADER.read_text(encoding="utf-8")
    return set(re.findall(r'#define\s+clo_\w+\s+"(-[^"]+)"', text))


def load_table():
    with open(TABLE, "rb") as f:
        return tomllib.load(f)["option"]


# Shown as literals: text the table marks with single backticks, option names, feature groups
# (*ALL_GLCM*) and feature-code families (IH_*).
LITERAL = re.compile(r"(`[^`]+`"
                     r"|(?<![\w-])--[A-Za-z][\w-]*(?:=[\w.,*/-]*[\w*])?"  # an option, with its value if given
                     r"|(?<![\w-])-h\b"
                     r"|\*[A-Za-z0-9_]+\*"
                     r"|\b[A-Z][A-Z0-9]*_\*)")


def escape(text):
    """Plain text -> reStructuredText: literals for code tokens, everything else escaped."""
    out = []
    for i, part in enumerate(LITERAL.split(text)):
        if i % 2:
            out.append(f"``{part.strip('`')}``")
            continue
        part = part.replace("\\", "\\\\")
        part = re.sub(r"([*|`])", r"\\\1", part)
        part = re.sub(r"(\w)_(?=\W|$)", r"\1\\_", part)  # a trailing underscore would make a link
        out.append(part)
    return "".join(out)


def cell(text):
    """One list-table cell: an empty cell is rendered as a dash."""
    text = " ".join(str(text).split())
    return escape(text) if text else "—"


def literal(text):
    return f"``{text}``" if text else "—"


def render(options):
    by_group = {g: [] for g in GROUPS}
    for o in options:
        if o["group"] not in by_group:
            raise SystemExit(f"{o['name']}: unknown group {o['group']!r}; expected one of {GROUPS}")
        by_group[o["group"]].append(o)

    out = [
        ".. This page is generated by docs/tools/gen_cli_reference.py from docs/cli_options.toml.",
        "   Edit the table and re-run the script; do not edit this file by hand.",
        "",
        ".. _cli-reference:",
        "",
        "Command-line reference",
        "======================",
        "",
        "Every option is written either as ``--option=value`` or as ``--option value``.",
        "Options marked *required* must be given on every run.",
        "",
    ]
    for group in GROUPS:
        rows = by_group[group]
        if not rows:
            continue
        out += [group, "-" * len(group), "", ".. list-table::", "   :header-rows: 1",
                "   :widths: 22 10 16 52", "",
                "   * - Option", "     - Required", "     - Default", "     - Description"]
        for o in rows:
            desc = o["summary"].strip()
            if o.get("values"):
                desc += f" Values: {o['values'].strip()}"
                desc += "" if desc.endswith(".") else "."
            if o.get("notes"):
                desc += " " + o["notes"].strip()
            if o.get("build"):
                desc += f" Available in {o['build'].strip()} only."
            out += [
                f"   * - ``{o['name']}``",
                f"     - {'yes' if o.get('required') else 'no'}",
                f"     - {literal(o.get('default', ''))}",
                f"     - {cell(desc)}",
            ]
        out.append("")
    return "\n".join(out).rstrip("\n")


def check_names(options):
    declared = cli_options()
    # An entry may name several spellings of one option, e.g. "-h, --help".
    listed = {n.strip() for o in options for n in o["name"].split(",")}
    problems = []
    for name in sorted(declared - listed):
        problems.append(f"{name} is defined in cli_option_constants.h but has no entry in {TABLE.name}")
    for name in sorted(listed - declared - BUILTIN):
        problems.append(f"{name} has an entry in {TABLE.name} but the CLI does not define it")
    names = [o["name"] for o in options]
    dupes = {n for n in names if names.count(n) > 1}
    for name in sorted(dupes):
        problems.append(f"{name} appears more than once in {TABLE.name}")
    return problems


SRC = REPO / "src" / "nyx"


def cited_lines(evidence):
    """The source lines an entry's evidence names: "file:12-14, 20; other.cpp:7 (note)".

    Returns (lines, problems); a cited file that does not exist, or a range that is not a line
    range of that file, is a problem.
    """
    lines, problems = [], []
    for part in evidence.split(";"):
        part = re.sub(r"\([^)]*\)", "", part).strip()  # drop "(explanations)"
        m = re.match(r"([\w./-]+):\s*(.+)$", part)
        if not m:
            continue
        path = SRC / m.group(1)
        if not path.exists():
            problems.append(f"cites {m.group(1)}, which does not exist")
            continue
        text = path.read_text(encoding="utf-8", errors="replace").splitlines()
        for rng in m.group(2).split(","):
            r = re.match(r"\s*(\d+)(?:-(\d+))?\s*$", rng)
            if not r or int(r.group(2) or r.group(1)) > len(text):
                problems.append(f"cites {m.group(1)}:{rng.strip()}, which is not a line range of that file")
                continue
            lines += text[int(r.group(1)) - 1:int(r.group(2) or r.group(1))]
    return lines, problems


def default_forms(default):
    """Ways the code may write a default: as given, or as another spelling of the same number."""
    d = default.strip()
    forms = {d}
    try:
        x = float(d)
    except ValueError:
        return forms
    if not math.isfinite(x):
        return forms
    forms |= {repr(x), f"{x:g}", f"{x:.0e}".replace("e+0", "e").replace("e+", "e")}
    if x == int(x):
        forms.add(str(int(x)))
    return forms


def assigned(form, text):
    """True when `form` is the value assigned or passed on this line: `x = 4;`, `x = "_";`, `push_back (0)`."""
    f = re.escape(form)
    return re.search(r'(?:(?<![!<>=])=|[{(])\s*"?' + f + r'"?\s*[;,})]', text) is not None


def check_defaults(options):
    """Every entry's evidence must cite existing files and line ranges. Every single-token default
    must be the value assigned on its `default_at` line (comments removed; a list default may also
    match with the spaces and braces removed). `default_at = "-"` opts an entry out."""
    problems = []
    for o in options:
        _, bad = cited_lines(o.get("evidence", ""))
        problems += [f"{o['name']}: {b}" for b in bad]
        default, at = o.get("default", "").strip(), o.get("default_at", "")
        if at == "-":
            continue
        if not at:
            if default and " " not in default:
                problems.append(f"{o['name']}: default {default!r} has no default_at line")
            continue
        lines, bad = cited_lines(at)
        problems += [f"{o['name']}: default_at {b}" for b in bad]
        if len(lines) != 1:
            problems.append(f"{o['name']}: default_at must name exactly one line")
            continue
        code = re.sub(r"//.*$", "", lines[0])
        squeezed = re.sub(r"\s", "", code)
        if not any(assigned(f, code)
                   or ("," in f and re.search(r'[{=]"?' + re.escape(f) + r'"?[;}]', squeezed))
                   for f in default_forms(default)):
            problems.append(f"{o['name']}: default {default!r} is not the value assigned at {at}")
    return problems

def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify instead of writing")
    args = ap.parse_args(argv)

    options = load_table()
    problems = check_names(options) + check_defaults(options)
    page = render(options) + "\n"

    if args.check:
        current = PAGE.read_text(encoding="utf-8") if PAGE.exists() else ""
        if current != page:
            problems.append(f"{PAGE.relative_to(REPO)} is stale; run docs/tools/gen_cli_reference.py")
        for p in problems:
            print(f"error: {p}", file=sys.stderr)
        return 1 if problems else 0

    for p in problems:
        print(f"error: {p}", file=sys.stderr)
    if problems:
        return 1
    PAGE.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {PAGE.relative_to(REPO)} ({len(options)} options)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
