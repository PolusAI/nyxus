// The pixel set a mask covers, in absolute coordinates once shifted by (x0, y0).
static std::set<std::pair<int, int>> contour_mask_pixels (const std::vector<std::string>& rows, int x0, int y0)
{
	std::set<std::pair<int, int>> S;
	for (int y = 0; y < (int)rows.size(); y++)
		for (int x = 0; x < (int)rows[y].size(); x++)
			if (rows[y][x] == '1')
				S.insert({ x0 + x, y0 + y });
	return S;
}

// A deterministic, non-constant intensity, so an EDGE_* statistic tells which pixels were visited
// and how often.
static unsigned int contour_fixture_intensity (int x, int y)
{
	return 1u + (unsigned int)((x * 7 + y * 13) % 50);
}

// Builds a single-ROI LR from a pixel set, the way phase 1 and phase 2 do for a trivial ROI.
static void contour_roi_from_pixels (LR& r, const std::set<std::pair<int, int>>& S)
{
	std::vector<NyxusPixel> px;
	for (const auto& p : S)
		px.push_back (NyxusPixel{ (size_t)p.first, (size_t)p.second, contour_fixture_intensity(p.first, p.second) });
	Nyxus::load_test_roi_data (r, px.data(), px.size());
	r.make_nonanisotropic_aabb();
}

// Runs ContourFeature on the ROI at the shape2d config and leaves the feature values in r.fvals.
static void contour_calculate (LR& r)
{
	Fsettings s = make_shape2d_settings();
	ContourFeature f;
	f.calculate (r, s);
	r.initialize_fvals();
	f.save_value (r.fvals);
}

// True when consecutive pixels of the closed walk K, including the last-to-first step, are 8-neighbours.
static bool contour_is_closed_8_walk (const std::vector<Pixel2>& K)
{
	for (size_t i = 0; i < K.size(); i++)
	{
		const Pixel2& a = K[i == 0 ? K.size() - 1 : i - 1], & b = K[i];
		if (std::abs((int)a.x - (int)b.x) > 1 || std::abs((int)a.y - (int)b.y) > 1)
			return false;
	}
	return true;
}

// Euclidean length of the closed walk K, the closing step included.
static double contour_closed_walk_length (const std::vector<Pixel2>& K)
{
	if (K.size() < 2)
		return 0.0;
	double len = 0.0;
	for (size_t i = 0; i < K.size(); i++)
		len += std::sqrt (K[i == 0 ? K.size() - 1 : i - 1].sqdist(K[i]));
	return len;
}

// The distinct pixels of every contour of the ROI.
static std::set<std::pair<int, int>> contour_pixel_set (const LR& r)
{
	std::set<std::pair<int, int>> S;
	for (const auto& K : r.multicontour_)
		for (const Pixel2& p : K)
			S.insert({ (int)p.x, (int)p.y });
	return S;
}
